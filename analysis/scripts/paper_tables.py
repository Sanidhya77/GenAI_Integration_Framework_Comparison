def lat_rows(n, ea, ids):
    rows, rels = [], []
    for ca, lab in CFGS:
        for k, (nm, st) in enumerate((("LM", "mean"), ("L50", "p50"), ("L95", "p95"))):
            cells = []
            for c in CS:
                base = f"{ea}.{ca}.c{c}"
                one = ca in ("flask", "django")
                cens = one and c >= 25
                steady = (one and c in (5, 10)) or (ca.endswith("17w") and c > 17)
                if cens:
                    if nm == "LM":
                        i = f"LR.{base}"
                        ids.append(i)
                        cells.append(rf"\textit{{{f(n.v(i), 0)}}}$^\dagger$")
                    else:
                        cells.append("cens.")
                    continue
                i = f"{nm}.{base}"
                ids.append(i)
                r = n.rel(i)
                rels.append(r)
                cells.append(f"{f(n.v(i), 0)}" + ("$^*$" if steady else ""))
            first = lab if k == 0 else ""
            rows.append(f"    {first} & {st} & " + " & ".join(cells) + r" \\")
        rows.append(r"    \addlinespace")
    rows.pop()
    return rows, max(rels)


LAT_CAPTION = r"""Latency (ms). $^*$ steady state: requests that started after the first queue cycle
  $t_0 + \lceil c/w \rceil S$ ($w$ = 1 or 17 workers), statistics pooled over the 5 runs. $^\dagger$ censored cell
  (one sync worker, $c \ge 25$): no request started after the first queue cycle completes inside the 60 s
  window, so the response-time law $R = N/X = c/X$ is shown (italic) and the measured percentiles (cens.) are
  not reported. Other cells: median over 5 runs of the per-run statistic over all requests (no queue forms).
  Interval half-widths (range of 5 runs; 95\,\%% bootstrap CI over whole runs for $^*$ cells) are at most %(rel)s\,\%% of
  the value in every printed cell."""


