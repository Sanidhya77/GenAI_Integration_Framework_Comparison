def read(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


class N:
    def __init__(self):
        self.n = {r["id"]: r for r in read(os.path.join(IN, "numbers.csv"))}
        self.used = []

    def v(self, i):
        self.used.append(i)
        return float(self.n[i]["value"])

    def ci(self, i):
        self.used.append(i)
        r = self.n[i]
        return (float(r["ci_low"]), float(r["ci_high"])) if r["ci_low"] else (None, None)

    def has(self, i):
        return i in self.n

    def rel(self, i):
        v, (lo, hi) = self.v(i), self.ci(i)
        return None if lo is None else (hi - lo) / 2 / abs(v)


def f(x, nd):
    return f"{x:,.{nd}f}"


def fx(x):
    """throughput: 3 decimals below 10 req/s, 2 above."""
    return f(x, 3) if x < 10 else f(x, 2)


def fci(n, i, nd, pct=False):
    v = n.v(i)
    lo, hi = n.ci(i)
    sgn = "+" if pct and v > 0 else ""
    s = f"{sgn}{f(v, nd)}"
    if lo is not None:
        s += f" [{f(lo, nd)}, {f(hi, nd)}]"
    return s


def write(dirn, name, body, ids):
    text = body.strip() + "\n"
    assert "\u2014" not in text and "\u2013" not in text
    head = (f"% {name}: generated by venv/bin/python analysis/scripts/paper_tables.py from "
            f"analysis/out/paper_v2.1/numbers.csv\n% numbers.csv ids: {compact(ids)}\n")
    with open(os.path.join(dirn, name), "w", encoding="utf-8") as fh:
        fh.write(head + text)


def compact(ids):
    ids = list(dict.fromkeys(ids))
    pre = sorted({i.split(".")[0] for i in ids})
    return f"{len(ids)} ids with prefixes " + ", ".join(pre) if len(ids) > 12 else ", ".join(ids)


